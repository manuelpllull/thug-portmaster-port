"""Generate portmaster/src/portmaster_glrec_gen.inc from a GLES 3.2 header.

usage: python gen_glrec.py gl32.h ../src/portmaster_glrec_gen.inc

Every GLES entry point gets:
  - a real pointer (glrec_real_<name>), resolved through the driver;
  - glrec_syncdirect_<name>: runs the real call on the render thread while the
    caller waits (used for anything returning a value or using pointers);
  - a stub glrec_<name>: direct call while the render thread is off; when it is
    on, an ASYNC record (void return and scalar args, or one copied payload) or
    the sync call;
  - a replay case for the async ones.
Functions in CUSTOM get their stub hand-written in portmaster_glrec.cpp (which
may call the generated glrec_async_<name> / glrec_syncdirect_<name>).
"""
import re
import sys

# pointer arg -> payload size (C expression over the arg names); NULL allowed
PAYLOAD = {
    'glBufferData': ('data', 'size'),
    'glBufferSubData': ('data', 'size'),
    'glCompressedTexImage2D': ('data', 'imageSize'),
    'glCompressedTexSubImage2D': ('data', 'imageSize'),
    'glCompressedTexImage3D': ('data', 'imageSize'),
    'glCompressedTexSubImage3D': ('data', 'imageSize'),
    'glTexImage2D': ('pixels', 'glrec_tex_bytes(width, height, 1, format, type)'),
    'glTexSubImage2D': ('pixels', 'glrec_tex_bytes(width, height, 1, format, type)'),
    'glTexImage3D': ('pixels', 'glrec_tex_bytes(width, height, depth, format, type)'),
    'glTexSubImage3D': ('pixels', 'glrec_tex_bytes(width, height, depth, format, type)'),
    'glUniform1fv': ('value', 'count * 4'), 'glUniform2fv': ('value', 'count * 8'),
    'glUniform3fv': ('value', 'count * 12'), 'glUniform4fv': ('value', 'count * 16'),
    'glUniform1iv': ('value', 'count * 4'), 'glUniform2iv': ('value', 'count * 8'),
    'glUniform3iv': ('value', 'count * 12'), 'glUniform4iv': ('value', 'count * 16'),
    'glUniform1uiv': ('value', 'count * 4'), 'glUniform2uiv': ('value', 'count * 8'),
    'glUniform3uiv': ('value', 'count * 12'), 'glUniform4uiv': ('value', 'count * 16'),
    'glUniformMatrix2fv': ('value', 'count * 16'), 'glUniformMatrix3fv': ('value', 'count * 36'),
    'glUniformMatrix4fv': ('value', 'count * 64'),
    'glUniformMatrix2x3fv': ('value', 'count * 24'), 'glUniformMatrix3x2fv': ('value', 'count * 24'),
    'glUniformMatrix2x4fv': ('value', 'count * 32'), 'glUniformMatrix4x2fv': ('value', 'count * 32'),
    'glUniformMatrix3x4fv': ('value', 'count * 48'), 'glUniformMatrix4x3fv': ('value', 'count * 48'),
    'glVertexAttrib1fv': ('v', '4'), 'glVertexAttrib2fv': ('v', '8'),
    'glVertexAttrib3fv': ('v', '12'), 'glVertexAttrib4fv': ('v', '16'),
    'glDeleteBuffers': ('buffers', 'n * 4'), 'glDeleteTextures': ('textures', 'n * 4'),
    'glDeleteFramebuffers': ('framebuffers', 'n * 4'), 'glDeleteRenderbuffers': ('renderbuffers', 'n * 4'),
    'glDeleteVertexArrays': ('arrays', 'n * 4'), 'glDeleteSamplers': ('samplers', 'count * 4'),
    'glDeleteQueries': ('ids', 'n * 4'),
    'glDrawBuffers': ('bufs', 'n * 4'),
    'glInvalidateFramebuffer': ('attachments', 'numAttachments * 4'),
    'glTexParameterfv': ('params', '16'), 'glTexParameteriv': ('params', '16'),
    'glSamplerParameterfv': ('param', '16'), 'glSamplerParameteriv': ('param', '16'),
    'glProgramBinary': ('binary', 'length'),
    'glClearBufferfv': ('value', '16'), 'glClearBufferiv': ('value', '16'),
    'glClearBufferuiv': ('value', '16'),
}
# hand-written stubs (shadow state, client arrays, fake error)
CUSTOM = {'glBindBuffer', 'glBindVertexArray', 'glPixelStorei', 'glVertexAttribPointer',
          'glVertexAttribIPointer', 'glEnableVertexAttribArray', 'glDisableVertexAttribArray',
          'glDrawElements', 'glDrawArrays', 'glGetError', 'glDeleteBuffers',
          'glDeleteVertexArrays', 'glGenBuffers', 'glGenTextures', 'glGenVertexArrays',
          'glEnable', 'glDisable', 'glIsEnabled'}

TYPES64 = {'GLint64', 'GLuint64'}
FLOATS = {'GLfloat', 'GLclampf'}
NL = '\n'

proto = re.compile(r'^GL_APICALL\s+(.+?)\s*GL_APIENTRY\s+(\w+)\s*\((.*)\);')


def parse_arg(a):
    a = a.strip()
    if a == 'void' or not a:
        return None
    m = re.match(r'^(.*?)(\w+)$', a)
    return m.group(1).strip(), m.group(2)


def main():
    src, out = sys.argv[1], sys.argv[2]
    funcs = []
    for line in open(src):
        m = proto.match(line.strip())
        if not m:
            continue
        ret, name, args = m.group(1).strip(), m.group(2), m.group(3)
        al = [x for x in (parse_arg(s) for s in args.split(',')) if x]
        funcs.append((ret, name, al))

    o = []
    w = o.append
    w('// GENERATED by portmaster/tools/gen_glrec.py from GLES3/gl32.h -- do not edit.')
    w('enum {')
    w('    GLREC_OP_NONE = 0,')
    for ret, name, al in funcs:
        w('    GLREC_OP_%s,' % name)
    w('    GLREC_OP_GEN_LAST')
    w('};')

    for ret, name, al in funcs:
        params = ', '.join('%s %s' % (t, n) for t, n in al) or 'void'
        w('typedef %s (GL_APIENTRY *glrec_pfn_%s)(%s);' % (ret, name, params))
        w('static glrec_pfn_%s glrec_real_%s;' % (name, name))

    replay = []
    for ret, name, al in funcs:
        params = ', '.join('%s %s' % (t, n) for t, n in al) or 'void'
        argn = ', '.join(n for t, n in al)
        scalar = all('*' not in t and t not in ('GLsync', 'GLDEBUGPROC') for t, n in al)
        payload = PAYLOAD.get(name)
        is_async = ret == 'void' and (scalar or (payload is not None and sum('*' in t for t, n in al) == 1))
        stub = 'glrec_%s' % name if name not in CUSTOM else 'glrec_gen_%s' % name

        # sync pieces, for every function
        fields = ' '.join('%s %s;' % (t, n) for t, n in al) or 'int unused_;'
        retf = ('%s ret_;' % ret) if ret != 'void' else ''
        w('struct glrec_args_%s { %s %s };' % (name, fields, retf))
        w('static void glrec_exec_%s(void *p)' % name)
        w('{')
        w('    glrec_args_%s *a = (glrec_args_%s *)p; (void)a;' % (name, name))
        callargs = ', '.join('a->%s' % n for t, n in al)
        if ret != 'void':
            w('    a->ret_ = glrec_real_%s(%s);' % (name, callargs))
        else:
            w('    glrec_real_%s(%s);' % (name, callargs))
        w('}')
        w('static %s glrec_syncdirect_%s(%s)' % (ret, name, params))
        w('{')
        w('    glrec_args_%s args_;' % name)
        for t, n in al:
            w('    args_.%s = %s;' % (n, n))
        w('    glrec_sync(glrec_exec_%s, &args_, "%s");' % (name, name))
        if ret != 'void':
            w('    return args_.ret_;')
        w('}')

        if is_async:
            nwords = 1 + sum(2 if t in TYPES64 else 1 for t, n in al if '*' not in t)
            w('static void glrec_async_%s(%s)' % (name, params))
            w('{')
            if payload:
                p, sz = payload
                w('    const uint32_t pay = %s ? (uint32_t)(%s) : 0u;' % (p, sz))
                w('    uint32_t *c = glrec_alloc(%d + 2, pay);' % nwords)
                w('    if (!c) { glrec_syncdirect_%s(%s); return; }' % (name, argn))
            else:
                w('    uint32_t *c = glrec_alloc(%d, 0);' % nwords)
            w('    uint32_t *q = c + 1;')
            for t, n in al:
                if '*' in t:
                    continue
                if t in TYPES64:
                    w('    memcpy(q, &%s, 8); q += 2;' % n)
                elif t in FLOATS:
                    w('    memcpy(q, &%s, 4); q += 1;' % n)
                else:
                    w('    *q++ = (uint32_t)%s;' % n)
            if payload:
                p, sz = payload
                w('    *q++ = %s ? 1u : 0u;' % p)
                w('    *q++ = pay;')
                w('    if (%s && pay) memcpy(q, %s, pay);' % (p, p))
            w('    glrec_commit(c, GLREC_OP_%s);' % name)
            w('}')
            r = ['    case GLREC_OP_%s: {' % name, '        const uint32_t *q = c + 1;']
            call = []
            for t, n in al:
                if '*' in t:
                    call.append('(%s)(hasp ? (const void *)(q + 2) : NULL)' % t)
                    continue
                if t in TYPES64:
                    r.append('        %s %s; memcpy(&%s, q, 8); q += 2;' % (t, n, n))
                elif t in FLOATS:
                    r.append('        %s %s; memcpy(&%s, q, 4); q += 1;' % (t, n, n))
                else:
                    r.append('        %s %s = (%s)*q++;' % (t, n, t))
                call.append(n)
            if payload:
                r.append('        const uint32_t hasp = q[0];')
            r.append('        glrec_real_%s(%s);' % (name, ', '.join(call)))
            r.append('        break; }')
            replay.extend(r)
            w('static void GL_APIENTRY %s(%s)' % (stub, params))
            w('{')
            w('    if (!glrec_deferred()) { glrec_real_%s(%s); return; }' % (name, argn))
            w('    glrec_async_%s(%s);' % (name, argn))
            w('}')
        else:
            w('static %s GL_APIENTRY %s(%s)' % (ret, stub, params))
            w('{')
            if ret != 'void':
                w('    if (!glrec_deferred()) return glrec_real_%s(%s);' % (name, argn))
                w('    return glrec_syncdirect_%s(%s);' % (name, argn))
            else:
                w('    if (!glrec_deferred()) { glrec_real_%s(%s); return; }' % (name, argn))
                w('    glrec_syncdirect_%s(%s);' % (name, argn))
            w('}')

    w('static void glrec_replay_generated(const uint32_t *c, uint32_t op)')
    w('{')
    w('    switch (op) {')
    o.extend(replay)
    w('    default: glrec_bad_op(op); break;')
    w('    }')
    w('}')
    w('struct glrec_entry { const char *name; void *stub; void **real; };')
    w('static const glrec_entry glrec_table[] = {')
    for ret, name, al in funcs:
        w('    { "%s", (void *)glrec_%s, (void **)&glrec_real_%s },' % (name, name, name))
    w('    { NULL, NULL, NULL }')
    w('};')
    open(out, 'w', newline='\n').write(NL.join(o) + NL)
    print('%d functions, %d replay lines' % (len(funcs), len(replay)))


if __name__ == '__main__':
    main()
